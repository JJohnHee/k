# -*- coding: utf-8 -*-
# 生成 setup.bat v2（CRLF），带批处理级重试循环，兼容老版 curl
lines = [
    '@echo off',
    'title SSH Kit Downloader v2',
    'cd /d "%~dp0"',
    'net session >nul 2>&1 || (',
    "    powershell -NoProfile -Command \"Start-Process -FilePath '%~f0' -Verb RunAs\"",
    '    exit /b',
    ')',
    'echo Cleaning partial files...',
    'del /q install-core.ps1 OpenSSH-Win64.zip tailscale-setup-1.104.7-amd64.msi keepawake-loop.ps1 >nul 2>&1',
    'set /a T=0',
    ':DL_CORE',
    'set /a T+=1',
    'curl -sS -o install-core.ps1 https://github.com/JJohnHee/k/releases/download/k/install-core.ps1',
    'if exist install-core.ps1 goto CORE_OK',
    'if %T% lss 6 (timeout /t 5 /nobreak >nul & goto DL_CORE)',
    ':CORE_OK',
    'echo install-core.ps1 done (try %T%)',
    'set /a T=0',
    ':DL_KEEP',
    'set /a T+=1',
    'curl -sS -o keepawake-loop.ps1 https://github.com/JJohnHee/k/releases/download/k/keepawake-loop.ps1',
    'if exist keepawake-loop.ps1 goto KEEP_OK',
    'if %T% lss 6 (timeout /t 3 /nobreak >nul & goto DL_KEEP)',
    ':KEEP_OK',
    'echo keepawake done (try %T%)',
    'set /a T=0',
    ':DL_SSH',
    'set /a T+=1',
    'curl -sS -o OpenSSH-Win64.zip https://github.com/JJohnHee/k/releases/download/k/OpenSSH-Win64.zip',
    'if not errorlevel 1 goto SSH_OK',
    'if %T% lss 8 (timeout /t 5 /nobreak >nul & goto DL_SSH)',
    ':SSH_OK',
    'echo openssh zip done (try %T%)',
    'set /a T=0',
    ':DL_MSI',
    'set /a T+=1',
    'curl -sS -o tailscale-setup-1.104.7-amd64.msi https://pkgs.tailscale.com/stable/tailscale-setup-1.104.7-amd64.msi',
    'for %%F in (tailscale-setup-1.104.7-amd64.msi) do set MS=%%~zF',
    'if %MS% GTR 20000000 goto MSI_OK',
    'del /q tailscale-setup-1.104.7-amd64.msi >nul 2>&1',
    'curl -sS -o tailscale-setup-1.104.7-amd64.msi https://github.com/JJohnHee/k/releases/download/k/tailscale-setup-1.104.7-amd64.msi',
    'for %%F in (tailscale-setup-1.104.7-amd64.msi) do set MS=%%~zF',
    'if %MS% GTR 20000000 goto MSI_OK',
    'if %T% lss 5 (timeout /t 8 /nobreak >nul & goto DL_MSI)',
    ':MSI_OK',
    'echo tailscale msi done (%MS% bytes, try %T%)',
    'echo All files ready. Running installer...',
    'powershell -NoProfile -ExecutionPolicy Bypass -File install-core.ps1',
    'echo.',
    'echo ============ DONE. See Desktop SSH-Kit-Result.txt ============',
    'pause',
]
with open(r'F:/天翼云电脑/kit-github/setup.bat', 'wb') as f:
    f.write(('\r\n'.join(lines) + '\r\n').encode('gbk', errors='replace'))
print('setup.bat v2 written, CRLF, gbk-safe')
